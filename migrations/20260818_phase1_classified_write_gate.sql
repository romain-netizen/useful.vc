  ADD COLUMN IF NOT EXISTS lifecycle_state text,
  ADD COLUMN IF NOT EXISTS proceeding_type text,
  ADD COLUMN IF NOT EXISTS additionality_state text,
  ADD COLUMN IF NOT EXISTS additionality_substitute text,
  ADD COLUMN IF NOT EXISTS additionality_dimension text,
  ADD COLUMN IF NOT EXISTS additionality_rationale text;

ALTER TABLE public.criterion_reviews
  ADD COLUMN IF NOT EXISTS fact_class text,
  ADD COLUMN IF NOT EXISTS writer_lane text,
  ADD COLUMN IF NOT EXISTS source_reference text;

ALTER TABLE public.secondary_criterion_reviews
  ADD COLUMN IF NOT EXISTS fact_class text,
