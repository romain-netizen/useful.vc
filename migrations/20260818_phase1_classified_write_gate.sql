CREATE OR REPLACE FUNCTION qa_monitor.detect_fact_class(p_claim text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  s text := lower(COALESCE(p_claim, ''));
BEGIN
  -- Exact regression signature: these 20 C8 rationales mixed entity liveness
  -- into a structural criterion, even when the status sentence mentions an acquisition.
  IF s ~ 'autonomy is structurally disqualifying or under review:' THEN
    RETURN 'liveness';
  END IF;

  IF s ~ 'publication_scope|out_of_scope'
     OR s ~ '\m(listed company|public company|ipo|euronext|nasdaq|nyse|acquired|acquisition|delisted)\M' THEN
    RETURN 'scope';
  END IF;

  IF s ~ 'cash runway|funding round|debt facility|financing condition|raised [€$£]|amount disclosed|exit amount' THEN
    RETURN 'finance';
  END IF;

  IF s ~ '\m(inactive|out of business|dissolved|forfeited|liquidated|liquidation|deregistered|bankrupt|insolvent|dormant)\M'
     OR s ~ 'safeguard procedure|under (court |judicial )?protection|redressement|continuation plan' THEN
    RETURN 'liveness';
  END IF;

  IF s ~ 'missed (its|the) .*primary endpoint'
     OR s ~ 'single-arm|lacked (a )?sham|sham control|could not attribute|efficacy uncertainty'
     OR s ~ 'meaning-changing errors|remain(s|ed)? unresolved'
     OR s ~ 'not (yet )?(validated|demonstrated|proven|commercialised|commercialized)'
     OR s ~ '(insufficient|limited|weak|missing|lacks?|without) (independent )?(evidence|validation|data|outcome|trial)'
     OR s ~ '(awaiting|pending) .*results|evidence[- ]maturity|readiness condition' THEN
    RETURN 'readiness';
  END IF;

  RETURN 'structural';
END
$$;

CREATE OR REPLACE FUNCTION qa_monitor.destination_for_fact_class(p_fact_class text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE p_fact_class
    WHEN 'structural' THEN 'criterion_reviews'
    WHEN 'readiness' THEN 'companies.what_it_needs_to_qualify'
    WHEN 'liveness' THEN 'companies.lifecycle_state'
    WHEN 'scope' THEN 'companies.publication_scope'
    WHEN 'finance' THEN 'company_funding/company_exit'
    ELSE 'rejected'
  END
$$;

CREATE OR REPLACE FUNCTION qa_monitor.record_claim_attempt(
  p_writer_lane text,
  p_company_id bigint,
  p_target_table text,
  p_target_criterion smallint,
  p_declared_fact_class text,
  p_detected_fact_class text,
  p_proposed_verdict text,
  p_claim_text text,
  p_payload jsonb,
  p_expected_destination text,
  p_outcome text,
  p_reason text,
  p_source_reference text
)
RETURNS void
LANGUAGE sql
AS $$
  INSERT INTO qa_monitor.claim_write_audit(
    writer_lane, company_id, company_name, target_table, target_criterion,
    declared_fact_class, detected_fact_class, proposed_verdict, claim_text,
    payload, expected_destination, outcome, reason, source_reference
  )
  VALUES (
    p_writer_lane,
    p_company_id,
    (SELECT name FROM public.companies WHERE id = p_company_id),
    p_target_table,
    p_target_criterion,
    p_declared_fact_class,
    p_detected_fact_class,
    p_proposed_verdict,
    p_claim_text,
    COALESCE(p_payload, '{}'::jsonb),
    p_expected_destination,
    p_outcome,
    p_reason,
    p_source_reference
  )
$$;

DROP FUNCTION IF EXISTS public.apply_classified_claim(
  bigint, text, text, text, text, smallint, text, bigint, jsonb
);

CREATE OR REPLACE FUNCTION public.apply_classified_claim(
  p_company_id bigint,
  p_writer_lane text,
  p_fact_class text,
  p_claim_text text,
  p_source_reference text DEFAULT NULL,
  p_criterion integer DEFAULT NULL,
  p_verdict text DEFAULT NULL,
  p_secondary_review_id bigint DEFAULT NULL,
  p_payload jsonb DEFAULT '{}'::jsonb
)
RETURNS TABLE(applied boolean, destination text, detected_fact_class text, reason text)
LANGUAGE plpgsql
AS $$
DECLARE
  v_detected text := qa_monitor.detect_fact_class(p_claim_text);
  v_destination text := qa_monitor.destination_for_fact_class(p_fact_class);
  v_methodology text;
  v_original_verdict text;
  v_actual_verdict text;
  v_actual_rationale text;
  v_actual_methodology text;
  v_scope text;
  v_lifecycle text;
  v_proceeding text;
  v_target text;
  v_amount numeric;
BEGIN
  p_payload := COALESCE(p_payload, '{}'::jsonb);
  applied := false;
  destination := v_destination;
  detected_fact_class := v_detected;
  reason := NULL;

  IF p_criterion IS NULL AND p_fact_class = 'structural' THEN
    destination := CASE p_payload->>'target'
      WHEN 'additionality' THEN 'companies.additionality'
      WHEN 'canonical_decision' THEN 'companies.public_state'
      ELSE v_destination
    END;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.companies WHERE id = p_company_id) THEN
    reason := 'company_not_found';
  ELSIF p_writer_lane IS NULL
        OR p_writer_lane NOT IN ('primary_automation', 'secondary_qa', 'human_adjudication') THEN
    reason := 'invalid_writer_lane';
  ELSIF p_fact_class IS NULL
        OR p_fact_class NOT IN ('structural', 'readiness', 'liveness', 'scope', 'finance') THEN
    reason := 'invalid_fact_class';
  ELSIF p_criterion IS NOT NULL AND p_fact_class <> 'structural' THEN
    reason := 'non_structural_fact_targeted_c1_c8';
  ELSIF p_criterion IS NOT NULL AND v_detected <> 'structural' THEN
    reason := 'phrase_guard_detected_' || v_detected;
  ELSIF p_criterion IS NOT NULL AND (p_criterion < 1 OR p_criterion > 8) THEN
    reason := 'invalid_criterion';
  ELSIF p_criterion IS NOT NULL
        AND (p_verdict IS NULL OR p_verdict NOT IN ('PASS', 'FAIL', 'UNCLEAR')) THEN
    reason := 'invalid_verdict';
  ELSIF p_criterion IS NULL AND p_fact_class = 'structural'
        AND COALESCE(p_payload->>'target', '') NOT IN ('additionality', 'canonical_decision') THEN
    reason := 'structural_claim_requires_criterion_additionality_or_canonical_target';
  END IF;

  IF reason IS NOT NULL THEN
    PERFORM qa_monitor.record_claim_attempt(
      p_writer_lane, p_company_id,
      CASE WHEN p_writer_lane = 'secondary_qa' THEN 'secondary_criterion_reviews' ELSE 'criterion_reviews' END,
      p_criterion::smallint, p_fact_class, v_detected, p_verdict, p_claim_text,
      p_payload, destination, 'rejected', reason, p_source_reference
    );
    RETURN NEXT;
    RETURN;
  END IF;

  IF p_writer_lane = 'primary_automation'
     AND p_fact_class <> 'finance'
     AND EXISTS (
       SELECT 1
       FROM public.companies
       WHERE id = p_company_id
         AND methodology_version ILIKE '%human-adjudicated%'
     ) THEN
    reason := 'human_adjudication_guard_neutralised_write';

    INSERT INTO qa_monitor.guard_audit(
      table_name, company_id, company_name, criterion, blocked_columns,
      attempted_methodology, old_values, attempted_values, db_user, application_name
    )
    SELECT
      CASE WHEN p_criterion IS NULL THEN 'companies' ELSE 'criterion_reviews' END,
      c.id,
      c.name,
      p_criterion::smallint,
      CASE
        WHEN p_criterion IS NOT NULL THEN ARRAY['verdict', 'rationale', 'methodology_version']::text[]
        WHEN p_fact_class = 'readiness' THEN ARRAY['what_it_needs_to_qualify']::text[]
        WHEN p_fact_class = 'liveness' THEN ARRAY['lifecycle_state', 'proceeding_type']::text[]
        WHEN p_fact_class = 'scope' THEN ARRAY['publication_scope']::text[]
        ELSE ARRAY['additionality']::text[]
      END,
      (SELECT value FROM public.system_config WHERE key = 'engine_version'),
      jsonb_build_object(
        'public_state', c.public_state,
        'methodology_version', c.methodology_version
      ),
      jsonb_build_object(
        'fact_class', p_fact_class,
        'verdict', p_verdict,
        'claim_text', p_claim_text,
        'payload', p_payload
      ),
      current_user,
      current_setting('application_name', true)
    FROM public.companies AS c
    WHERE c.id = p_company_id;

    PERFORM qa_monitor.record_claim_attempt(
      p_writer_lane, p_company_id,
      CASE WHEN p_criterion IS NULL THEN destination ELSE 'criterion_reviews' END,
      p_criterion::smallint, p_fact_class, v_detected, p_verdict, p_claim_text,
      p_payload, destination, 'rejected', reason, p_source_reference
    );
    RETURN NEXT;
    RETURN;
  END IF;

  IF p_criterion IS NOT NULL THEN
    IF p_writer_lane = 'secondary_qa' THEN
      IF p_secondary_review_id IS NULL OR NOT EXISTS (
        SELECT 1
        FROM public.secondary_company_reviews
        WHERE id = p_secondary_review_id AND company_id = p_company_id
      ) THEN
        reason := 'secondary_review_not_found_for_company';
      ELSE
        SELECT verdict INTO v_original_verdict
        FROM public.criterion_reviews
        WHERE company_id = p_company_id AND criterion = p_criterion;

        PERFORM set_config('qa_monitor.claim_gate_authorized', '1', true);
        INSERT INTO public.secondary_criterion_reviews(
          secondary_review_id, criterion, original_verdict, proposed_verdict,
          agreement, rationale, missing_evidence, fact_class, writer_lane, source_reference
        )
        VALUES (
          p_secondary_review_id, p_criterion, v_original_verdict, p_verdict,
          v_original_verdict IS NOT DISTINCT FROM p_verdict,
          p_claim_text, p_payload->>'missing_evidence', 'structural', p_writer_lane, p_source_reference
        )
        ON CONFLICT (secondary_review_id, criterion) DO UPDATE SET
          original_verdict = excluded.original_verdict,
          proposed_verdict = excluded.proposed_verdict,
          agreement = excluded.agreement,
          rationale = excluded.rationale,
          missing_evidence = excluded.missing_evidence,
          fact_class = excluded.fact_class,
          writer_lane = excluded.writer_lane,
          source_reference = excluded.source_reference;
        PERFORM set_config('qa_monitor.claim_gate_authorized', '0', true);
        applied := true;
        destination := 'secondary_criterion_reviews';
      END IF;
    ELSE
      v_methodology := COALESCE(
        NULLIF(p_payload->>'methodology_version', ''),
        (SELECT value FROM public.system_config WHERE key = 'engine_version')
      );

      PERFORM set_config('qa_monitor.claim_gate_authorized', '1', true);
      INSERT INTO public.criterion_reviews(
        company_id, criterion, verdict, rationale, reviewed_at, methodology_version,
        fact_class, writer_lane, source_reference
      )
      VALUES (
        p_company_id, p_criterion, p_verdict, p_claim_text, now(), v_methodology,
        'structural', p_writer_lane, p_source_reference
      )
      ON CONFLICT (company_id, criterion) DO UPDATE SET
        verdict = excluded.verdict,
        rationale = excluded.rationale,
        reviewed_at = excluded.reviewed_at,
        methodology_version = excluded.methodology_version,
        fact_class = excluded.fact_class,
        writer_lane = excluded.writer_lane,
        source_reference = excluded.source_reference;
      PERFORM set_config('qa_monitor.claim_gate_authorized', '0', true);

      SELECT verdict, rationale, methodology_version
      INTO v_actual_verdict, v_actual_rationale, v_actual_methodology
      FROM public.criterion_reviews
      WHERE company_id = p_company_id AND criterion = p_criterion;

      IF v_actual_verdict IS DISTINCT FROM p_verdict
         OR v_actual_rationale IS DISTINCT FROM p_claim_text
         OR v_actual_methodology IS DISTINCT FROM v_methodology THEN
        reason := 'human_adjudication_guard_neutralised_write';
      ELSE
        applied := true;
        destination := 'criterion_reviews';
      END IF;
    END IF;
  ELSIF p_fact_class = 'structural' THEN
    IF p_payload->>'target' = 'additionality' THEN
      IF p_payload->>'additionality_state' IS NULL
         OR p_payload->>'additionality_state' NOT IN ('demonstrated', 'plausible', 'weak')
         OR COALESCE(NULLIF(p_payload->>'substitute', ''), '') = ''
         OR COALESCE(NULLIF(p_payload->>'dimension', ''), '') = '' THEN
        reason := 'additionality_requires_state_substitute_and_dimension';
      ELSE
        PERFORM set_config('qa_monitor.claim_gate_authorized', '1', true);
        UPDATE public.companies
        SET additionality_state = p_payload->>'additionality_state',
            additionality_substitute = p_payload->>'substitute',
            additionality_dimension = p_payload->>'dimension',
            additionality_rationale = p_claim_text,
            updated_at = now()
        WHERE id = p_company_id;
        PERFORM set_config('qa_monitor.claim_gate_authorized', '0', true);
        applied := true;
        destination := 'companies.additionality';
      END IF;
    ELSIF p_payload->>'target' = 'canonical_decision' THEN
      IF p_payload->>'public_state' IS NULL
         OR p_payload->>'public_state' NOT IN ('Main', 'Pending', 'Excluded') THEN
        reason := 'canonical_decision_requires_valid_public_state';
      ELSE
        v_methodology := COALESCE(
          NULLIF(p_payload->>'methodology_version', ''),
          (SELECT value FROM public.system_config WHERE key = 'engine_version')
        );
        PERFORM set_config('qa_monitor.claim_gate_authorized', '1', true);
        UPDATE public.companies
        SET public_state = p_payload->>'public_state',
            publishable = (p_payload->>'public_state') <> 'Excluded',
            methodology_version = v_methodology,
            last_reviewed = current_date,
            updated_at = now()
        WHERE id = p_company_id;
        PERFORM set_config('qa_monitor.claim_gate_authorized', '0', true);
        applied := true;
        destination := 'companies.public_state';
      END IF;
    ELSE
      reason := 'invalid_structural_target';
    END IF;
  ELSIF p_fact_class = 'readiness' THEN
    IF p_writer_lane = 'secondary_qa' THEN
      IF p_secondary_review_id IS NULL OR NOT EXISTS (
        SELECT 1 FROM public.secondary_company_reviews
        WHERE id = p_secondary_review_id AND company_id = p_company_id
      ) THEN
        reason := 'secondary_review_not_found_for_company';
      ELSE
        UPDATE public.secondary_company_reviews
        SET what_first_pass_should_do_next_time = CASE
          WHEN COALESCE(NULLIF(p_payload->>'clear', '')::boolean, false) THEN NULL
          ELSE p_claim_text
        END
        WHERE id = p_secondary_review_id;
        applied := true;
        destination := 'secondary_company_reviews.what_first_pass_should_do_next_time';
      END IF;
    ELSE
      PERFORM set_config('qa_monitor.claim_gate_authorized', '1', true);
      UPDATE public.companies
      SET what_it_needs_to_qualify = CASE
            WHEN COALESCE(NULLIF(p_payload->>'clear', '')::boolean, false) THEN NULL
            ELSE p_claim_text
          END,
          updated_at = now()
      WHERE id = p_company_id;
      PERFORM set_config('qa_monitor.claim_gate_authorized', '0', true);
      applied := true;
      destination := 'companies.what_it_needs_to_qualify';
    END IF;
  ELSIF p_fact_class = 'liveness' THEN
    v_lifecycle := NULLIF(p_payload->>'lifecycle_state', '');
    v_proceeding := NULLIF(p_payload->>'proceeding_type', '');
    IF v_lifecycle IS NULL OR v_lifecycle NOT IN (
      'active', 'active_under_protection', 'wound_down',
      'insolvent_liquidated', 'dormant', 'unknown'
    ) THEN
      reason := 'invalid_or_missing_lifecycle_state';
    ELSIF v_proceeding IS NOT NULL
          AND v_proceeding NOT IN ('sauvegarde', 'redressement', 'continuation_plan') THEN
      reason := 'invalid_proceeding_type';
    ELSIF p_writer_lane = 'secondary_qa' THEN
      IF p_secondary_review_id IS NULL OR NOT EXISTS (
        SELECT 1 FROM public.secondary_company_reviews
        WHERE id = p_secondary_review_id AND company_id = p_company_id
      ) THEN
        reason := 'secondary_review_not_found_for_company';
      ELSE
        UPDATE public.secondary_company_reviews
        SET proposed_lifecycle_state = v_lifecycle,
            proposed_proceeding_type = v_proceeding,
            entity_status_rationale = p_claim_text
        WHERE id = p_secondary_review_id;
        applied := true;
        destination := 'secondary_company_reviews.proposed_lifecycle_state';
      END IF;
    ELSE
      PERFORM set_config('qa_monitor.claim_gate_authorized', '1', true);
      UPDATE public.companies
      SET lifecycle_state = v_lifecycle,
          proceeding_type = v_proceeding,
          operating_status = COALESCE(NULLIF(p_payload->>'operating_status', ''), operating_status),
          status_source_url = COALESCE(NULLIF(p_payload->>'status_source_url', ''), status_source_url),
          status_checked_at = COALESCE(NULLIF(p_payload->>'status_checked_at', '')::date, status_checked_at),
          updated_at = now()
      WHERE id = p_company_id;
      PERFORM set_config('qa_monitor.claim_gate_authorized', '0', true);
      applied := true;
      destination := 'companies.lifecycle_state';
    END IF;
  ELSIF p_fact_class = 'scope' THEN
    v_scope := NULLIF(p_payload->>'publication_scope', '');
    IF v_scope IS NULL OR v_scope NOT IN ('in_scope', 'listed', 'acquired') THEN
      reason := 'invalid_or_abolished_publication_scope';
    ELSIF p_writer_lane = 'secondary_qa' THEN
      IF p_secondary_review_id IS NULL OR NOT EXISTS (
        SELECT 1 FROM public.secondary_company_reviews
        WHERE id = p_secondary_review_id AND company_id = p_company_id
      ) THEN
        reason := 'secondary_review_not_found_for_company';
      ELSE
        UPDATE public.secondary_company_reviews
        SET proposed_publication_scope = v_scope
        WHERE id = p_secondary_review_id;
        applied := true;
        destination := 'secondary_company_reviews.proposed_publication_scope';
      END IF;
    ELSE
      PERFORM set_config('qa_monitor.claim_gate_authorized', '1', true);
      UPDATE public.companies
      SET publication_scope = v_scope, updated_at = now()
      WHERE id = p_company_id;
      PERFORM set_config('qa_monitor.claim_gate_authorized', '0', true);
      applied := true;
      destination := 'companies.publication_scope';
    END IF;
  ELSIF p_fact_class = 'finance' THEN
    IF p_writer_lane = 'secondary_qa' THEN
      reason := 'secondary_finance_claim_requires_manual_primary_source_review';
    ELSIF COALESCE(NULLIF(p_payload->>'source_url', ''), '') = '' THEN
      reason := 'finance_requires_primary_source_url';
    ELSE
      v_target := p_payload->>'target';
      v_amount := NULLIF(p_payload->>'amount', '')::numeric;
      IF v_target = 'funding' THEN
        INSERT INTO public.company_funding(
          company_id, round_type, announced_on, amount, currency,
          amount_disclosed, source_url
        ) VALUES (
          p_company_id, p_payload->>'round_type',
          NULLIF(p_payload->>'announced_on', '')::date,
          v_amount, p_payload->>'currency',
          COALESCE(NULLIF(p_payload->>'amount_disclosed', '')::boolean, false),
          p_payload->>'source_url'
        );
        applied := true;
        destination := 'company_funding';
      ELSIF v_target = 'exit' THEN
        INSERT INTO public.company_exit(
          company_id, exit_type, announced_on, amount, currency,
          amount_disclosed, acquirer, source_url
        ) VALUES (
          p_company_id, p_payload->>'exit_type',
          NULLIF(p_payload->>'announced_on', '')::date,
          v_amount, p_payload->>'currency',
          COALESCE(NULLIF(p_payload->>'amount_disclosed', '')::boolean, false),
          p_payload->>'acquirer', p_payload->>'source_url'
        );
        applied := true;
        destination := 'company_exit';
      ELSE
        reason := 'finance_target_must_be_funding_or_exit';
      END IF;
    END IF;
  END IF;

  PERFORM qa_monitor.record_claim_attempt(
    p_writer_lane, p_company_id,
    CASE
      WHEN p_criterion IS NOT NULL AND p_writer_lane = 'secondary_qa' THEN 'secondary_criterion_reviews'
      WHEN p_criterion IS NOT NULL THEN 'criterion_reviews'
      ELSE destination
    END,
    p_criterion::smallint, p_fact_class, v_detected, p_verdict, p_claim_text,
    p_payload, destination,
    CASE WHEN applied THEN 'applied' ELSE 'rejected' END,
    reason, p_source_reference
  );

  RETURN NEXT;
END
$$;

CREATE OR REPLACE FUNCTION qa_monitor.fn_block_direct_claim_dml()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_company_id bigint;
  v_criterion smallint;
  v_fact_class text;
  v_writer text;
  v_claim text;
  v_verdict text;
  v_source text;
BEGIN
  IF current_setting('qa_monitor.claim_gate_authorized', true) = '1' THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
  END IF;

  IF TG_TABLE_NAME = 'criterion_reviews' THEN
    IF TG_OP = 'DELETE' THEN
      v_company_id := OLD.company_id;
      v_criterion := OLD.criterion;
      v_fact_class := OLD.fact_class;
      v_writer := OLD.writer_lane;
      v_claim := OLD.rationale;
      v_verdict := OLD.verdict;
      v_source := OLD.source_reference;
    ELSE
      v_company_id := NEW.company_id;
      v_criterion := NEW.criterion;
      v_fact_class := NEW.fact_class;
      v_writer := NEW.writer_lane;
      v_claim := NEW.rationale;
      v_verdict := NEW.verdict;
      v_source := NEW.source_reference;
    END IF;
  ELSE
    IF TG_OP = 'DELETE' THEN
      SELECT company_id INTO v_company_id
      FROM public.secondary_company_reviews
      WHERE id = OLD.secondary_review_id;
      v_criterion := OLD.criterion;
      v_fact_class := OLD.fact_class;
      v_writer := OLD.writer_lane;
      v_claim := OLD.rationale;
      v_verdict := OLD.proposed_verdict;
      v_source := OLD.source_reference;
    ELSE
      SELECT company_id INTO v_company_id
      FROM public.secondary_company_reviews
      WHERE id = NEW.secondary_review_id;
      v_criterion := NEW.criterion;
      v_fact_class := NEW.fact_class;
      v_writer := NEW.writer_lane;
      v_claim := NEW.rationale;
      v_verdict := NEW.proposed_verdict;
      v_source := NEW.source_reference;
    END IF;
  END IF;

  PERFORM qa_monitor.record_claim_attempt(
    COALESCE(v_writer, 'unknown_direct_writer'), v_company_id, TG_TABLE_NAME,
    v_criterion, v_fact_class, qa_monitor.detect_fact_class(v_claim),
    v_verdict, v_claim, '{}'::jsonb,
    qa_monitor.destination_for_fact_class(v_fact_class),
    'rejected', 'direct_criterion_dml_forbidden', v_source
  );

  IF TG_OP = 'INSERT' OR TG_OP = 'DELETE' THEN
    RETURN NULL;
  END IF;
  RETURN OLD;
END
$$;

