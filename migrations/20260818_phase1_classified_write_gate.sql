CREATE OR REPLACE FUNCTION qa_monitor.fn_block_direct_company_claim_dml()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_changed text[] := ARRAY[]::text[];
BEGIN
  IF current_setting('qa_monitor.claim_gate_authorized', true) = '1' THEN
    RETURN NEW;
  END IF;

  IF NEW.public_state IS DISTINCT FROM OLD.public_state THEN v_changed := array_append(v_changed, 'public_state'); END IF;
  IF NEW.publishable IS DISTINCT FROM OLD.publishable THEN v_changed := array_append(v_changed, 'publishable'); END IF;
  IF NEW.what_it_needs_to_qualify IS DISTINCT FROM OLD.what_it_needs_to_qualify THEN v_changed := array_append(v_changed, 'what_it_needs_to_qualify'); END IF;
  IF NEW.methodology_version IS DISTINCT FROM OLD.methodology_version THEN v_changed := array_append(v_changed, 'methodology_version'); END IF;
  IF NEW.last_reviewed IS DISTINCT FROM OLD.last_reviewed THEN v_changed := array_append(v_changed, 'last_reviewed'); END IF;
  IF NEW.lifecycle_state IS DISTINCT FROM OLD.lifecycle_state THEN v_changed := array_append(v_changed, 'lifecycle_state'); END IF;
  IF NEW.proceeding_type IS DISTINCT FROM OLD.proceeding_type THEN v_changed := array_append(v_changed, 'proceeding_type'); END IF;
  IF NEW.operating_status IS DISTINCT FROM OLD.operating_status THEN v_changed := array_append(v_changed, 'operating_status'); END IF;
  IF NEW.status_source_url IS DISTINCT FROM OLD.status_source_url THEN v_changed := array_append(v_changed, 'status_source_url'); END IF;
  IF NEW.status_checked_at IS DISTINCT FROM OLD.status_checked_at THEN v_changed := array_append(v_changed, 'status_checked_at'); END IF;
  IF NEW.publication_scope IS DISTINCT FROM OLD.publication_scope THEN v_changed := array_append(v_changed, 'publication_scope'); END IF;
  IF NEW.additionality_state IS DISTINCT FROM OLD.additionality_state THEN v_changed := array_append(v_changed, 'additionality_state'); END IF;
  IF NEW.additionality_substitute IS DISTINCT FROM OLD.additionality_substitute THEN v_changed := array_append(v_changed, 'additionality_substitute'); END IF;
  IF NEW.additionality_dimension IS DISTINCT FROM OLD.additionality_dimension THEN v_changed := array_append(v_changed, 'additionality_dimension'); END IF;
  IF NEW.additionality_rationale IS DISTINCT FROM OLD.additionality_rationale THEN v_changed := array_append(v_changed, 'additionality_rationale'); END IF;

  IF array_length(v_changed, 1) IS NULL THEN
    RETURN NEW;
  END IF;

  PERFORM qa_monitor.record_claim_attempt(
    'unknown_direct_writer', OLD.id, 'companies', NULL,
    NULL, 'structural', NULL, NULL,
    jsonb_build_object(
      'blocked_columns', to_jsonb(v_changed),
      'attempted_public_state', NEW.public_state,
      'attempted_methodology_version', NEW.methodology_version
    ),
    'public.apply_classified_claim', 'rejected',
    'direct_classification_company_dml_forbidden', NULL
  );

  IF OLD.methodology_version ILIKE '%human-adjudicated%' THEN
    INSERT INTO qa_monitor.guard_audit(
      table_name, company_id, company_name, blocked_columns,
      attempted_methodology, old_values, attempted_values, db_user, application_name
    )
    VALUES (
      'companies', OLD.id, OLD.name, v_changed, NEW.methodology_version,
      jsonb_build_object(
        'public_state', OLD.public_state,
        'publishable', OLD.publishable,
        'methodology_version', OLD.methodology_version
      ),
      jsonb_build_object(
        'public_state', NEW.public_state,
        'publishable', NEW.publishable,
        'methodology_version', NEW.methodology_version
      ),
      current_user, current_setting('application_name', true)
    );
  END IF;

  NEW.public_state := OLD.public_state;
  NEW.publishable := OLD.publishable;
  NEW.what_it_needs_to_qualify := OLD.what_it_needs_to_qualify;
  NEW.methodology_version := OLD.methodology_version;
  NEW.last_reviewed := OLD.last_reviewed;
  NEW.lifecycle_state := OLD.lifecycle_state;
  NEW.proceeding_type := OLD.proceeding_type;
  NEW.operating_status := OLD.operating_status;
  NEW.status_source_url := OLD.status_source_url;
  NEW.status_checked_at := OLD.status_checked_at;
  NEW.publication_scope := OLD.publication_scope;
  NEW.additionality_state := OLD.additionality_state;
  NEW.additionality_substitute := OLD.additionality_substitute;
  NEW.additionality_dimension := OLD.additionality_dimension;
  NEW.additionality_rationale := OLD.additionality_rationale;
  NEW.updated_at := OLD.updated_at;
  RETURN NEW;
END
$$;

