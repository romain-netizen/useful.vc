CREATE OR REPLACE FUNCTION qa_monitor.fn_validate_human_adjudication_stamp()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_company_id bigint;
  v_company_name text;
  v_criterion smallint;
  v_feedback_id bigint;
  v_path text;
  v_expected_methodology text;
  v_source_reference text;
  v_is_new_stamp boolean;
  v_reason text;
BEGIN
  IF TG_TABLE_NAME = 'companies' THEN
    v_company_id := NEW.id;
    v_company_name := NEW.name;
    v_criterion := NULL;
    v_source_reference := current_setting('qa_monitor.human_source_reference', true);
  ELSE
    v_company_id := NEW.company_id;
    v_company_name := (SELECT name FROM public.companies WHERE id = NEW.company_id);
    v_criterion := NEW.criterion;
    v_source_reference := NEW.source_reference;
  END IF;

  IF NEW.methodology_version IS NULL
     OR NEW.methodology_version NOT ILIKE '%human-adjudicated%' THEN
    NEW.human_adjudication_feedback_id := NULL;
    NEW.human_adjudication_path := NULL;
    RETURN NEW;
  END IF;

  BEGIN
    v_feedback_id := NULLIF(
      current_setting('qa_monitor.human_feedback_id', true), ''
    )::bigint;
  EXCEPTION WHEN invalid_text_representation THEN
    v_feedback_id := NULL;
  END;
  v_path := NULLIF(current_setting('qa_monitor.human_adjudication_path', true), '');

  IF v_feedback_id IS NULL THEN
    v_reason := 'human_stamp_requires_feedback_context';
  ELSIF v_path IS NULL OR v_path NOT IN (
    'vercel_adjudication', 'migration', 'manual', 'legacy_unrecorded'
  ) THEN
    v_reason := 'human_stamp_requires_valid_application_path';
  ELSE
    SELECT CASE rf.decision
      WHEN 'custom' THEN 'v5 — human-adjudicated custom'
      WHEN 'primary_correct' THEN 'v5 — human-adjudicated primary'
      WHEN 'secondary_correct' THEN 'v5 — human-adjudicated QA'
    END
    INTO v_expected_methodology
    FROM public.review_feedback AS rf
    WHERE rf.id = v_feedback_id
      AND rf.company_id = v_company_id;

    IF v_expected_methodology IS NULL THEN
      v_reason := 'human_stamp_feedback_not_found_for_company';
    ELSIF NEW.methodology_version IS DISTINCT FROM v_expected_methodology THEN
      v_reason := 'human_stamp_methodology_disagrees_with_feedback_decision';
    END IF;
  END IF;

  IF v_reason IS NOT NULL THEN
    INSERT INTO qa_monitor.human_adjudication_audit(
      event_kind, target_table, company_id, company_name, criterion, feedback_id,
      adjudication_path, prior_methodology_version, methodology_version,
      source_reference, details
    ) VALUES (
      'stamp_rejected', TG_TABLE_NAME, v_company_id, v_company_name, v_criterion,
      v_feedback_id, v_path,
      CASE WHEN TG_OP = 'UPDATE' THEN OLD.methodology_version ELSE NULL END,
      NEW.methodology_version, v_source_reference,
      jsonb_build_object('reason', v_reason, 'operation', TG_OP)
    );

    IF TG_OP = 'INSERT' THEN RETURN NULL; END IF;
    RETURN OLD;
  END IF;

  NEW.human_adjudication_feedback_id := v_feedback_id;
  NEW.human_adjudication_path := v_path;
  -- INSERT ... ON CONFLICT fires the BEFORE INSERT trigger and then the BEFORE
  -- UPDATE trigger. When the criterion already exists, audit only the real
  -- UPDATE event so one adjudication write produces one provenance row.
  v_is_new_stamp := NOT (
      TG_TABLE_NAME = 'criterion_reviews'
      AND TG_OP = 'INSERT'
      AND EXISTS (
        SELECT 1 FROM public.criterion_reviews
        WHERE company_id = v_company_id AND criterion = v_criterion
      )
    ) AND (
      TG_OP = 'INSERT'
      OR OLD.methodology_version IS DISTINCT FROM NEW.methodology_version
      OR OLD.human_adjudication_feedback_id IS DISTINCT FROM v_feedback_id
      OR OLD.human_adjudication_path IS DISTINCT FROM v_path
    );

  IF v_is_new_stamp THEN
    INSERT INTO qa_monitor.human_adjudication_audit(
      event_kind, target_table, company_id, company_name, criterion, feedback_id,
      adjudication_path, prior_methodology_version, methodology_version,
      source_reference, details
    ) VALUES (
      'stamp_applied', TG_TABLE_NAME, v_company_id, v_company_name, v_criterion,
      v_feedback_id, v_path,
      CASE WHEN TG_OP = 'UPDATE' THEN OLD.methodology_version ELSE NULL END,
      NEW.methodology_version, v_source_reference,
      jsonb_build_object('operation', TG_OP)
    );
  END IF;

  RETURN NEW;
END
$$;

