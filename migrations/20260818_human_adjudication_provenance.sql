CREATE OR REPLACE VIEW qa_monitor.v_human_adjudication_provenance AS
WITH stamped AS (
  SELECT
    'companies'::text AS target_table,
    c.id AS company_id,
    c.name AS company_name,
    NULL::smallint AS criterion,
    c.methodology_version,
    c.human_adjudication_feedback_id AS feedback_id,
    c.human_adjudication_path AS adjudication_path
  FROM public.companies AS c
  WHERE c.methodology_version ILIKE '%human-adjudicated%'
  UNION ALL
  SELECT
    'criterion_reviews', cr.company_id, c.name, cr.criterion,
    cr.methodology_version, cr.human_adjudication_feedback_id,
    cr.human_adjudication_path
  FROM public.criterion_reviews AS cr
  JOIN public.companies AS c ON c.id = cr.company_id
  WHERE cr.methodology_version ILIKE '%human-adjudicated%'
)
SELECT
  s.*,
  rf.secondary_review_id,
  rf.decision,
  rf.created_at AS feedback_created_at,
  (
    rf.id IS NOT NULL
    AND rf.company_id = s.company_id
    AND s.adjudication_path IS NOT NULL
    AND s.methodology_version = CASE rf.decision
      WHEN 'custom' THEN 'v5 — human-adjudicated custom'
      WHEN 'primary_correct' THEN 'v5 — human-adjudicated primary'
      WHEN 'secondary_correct' THEN 'v5 — human-adjudicated QA'
    END
  ) AS provenance_valid
FROM stamped AS s
LEFT JOIN public.review_feedback AS rf ON rf.id = s.feedback_id;

CREATE OR REPLACE VIEW qa_monitor.v_human_adjudication_orphans AS
SELECT *
FROM qa_monitor.v_human_adjudication_provenance
WHERE NOT provenance_valid;

