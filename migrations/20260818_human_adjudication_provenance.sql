-- The only route that establishes the transaction-local feedback and path
-- context consumed by the validation trigger above.
CREATE OR REPLACE FUNCTION public.apply_human_adjudication_claim(
  p_company_id bigint,
  p_feedback_id bigint,
  p_adjudication_path text,
  p_fact_class text,
  p_claim_text text,
  p_source_reference text DEFAULT NULL,
  p_criterion integer DEFAULT NULL,
  p_verdict text DEFAULT NULL,
  p_secondary_review_id bigint DEFAULT NULL,
  p_payload jsonb DEFAULT '{}'::jsonb
)
RETURNS TABLE(applied boolean, destination text, detected_fact_class text, reason text)
LANGUAGE plpgsql
AS $$
DECLARE
  v_decision text;
  v_expected_methodology text;
BEGIN
  IF p_adjudication_path NOT IN ('vercel_adjudication', 'migration', 'manual') THEN
    RETURN QUERY SELECT false, NULL::text, qa_monitor.detect_fact_class(p_claim_text),
      'invalid_human_adjudication_path'::text;
    RETURN;
  END IF;

  SELECT rf.decision
  INTO v_decision
  FROM public.review_feedback AS rf
  WHERE rf.id = p_feedback_id
    AND rf.company_id = p_company_id
    AND (p_secondary_review_id IS NULL OR rf.secondary_review_id = p_secondary_review_id);

  IF v_decision IS NULL THEN
    RETURN QUERY SELECT false, NULL::text, qa_monitor.detect_fact_class(p_claim_text),
      'review_feedback_not_found_for_company'::text;
    RETURN;
  END IF;

  v_expected_methodology := CASE v_decision
    WHEN 'custom' THEN 'v5 — human-adjudicated custom'
    WHEN 'primary_correct' THEN 'v5 — human-adjudicated primary'
    WHEN 'secondary_correct' THEN 'v5 — human-adjudicated QA'
  END;

  IF (p_criterion IS NOT NULL OR COALESCE(p_payload->>'target', '') = 'canonical_decision')
     AND NULLIF(p_payload->>'methodology_version', '') IS DISTINCT FROM v_expected_methodology THEN
    RETURN QUERY SELECT false, NULL::text, qa_monitor.detect_fact_class(p_claim_text),
      'methodology_disagrees_with_feedback_decision'::text;
    RETURN;
  END IF;

  PERFORM set_config('qa_monitor.human_feedback_id', p_feedback_id::text, true);
  PERFORM set_config('qa_monitor.human_adjudication_path', p_adjudication_path, true);
  PERFORM set_config('qa_monitor.human_source_reference', COALESCE(p_source_reference, ''), true);

  RETURN QUERY
  SELECT * FROM public.apply_classified_claim(
    p_company_id,
    'human_adjudication',
    p_fact_class,
    p_claim_text,
    p_source_reference,
    p_criterion,
    p_verdict,
    p_secondary_review_id,
    COALESCE(p_payload, '{}'::jsonb)
  );

  PERFORM set_config('qa_monitor.human_feedback_id', '', true);
  PERFORM set_config('qa_monitor.human_adjudication_path', '', true);
  PERFORM set_config('qa_monitor.human_source_reference', '', true);
EXCEPTION WHEN OTHERS THEN
  PERFORM set_config('qa_monitor.human_feedback_id', '', true);
  PERFORM set_config('qa_monitor.human_adjudication_path', '', true);
  PERFORM set_config('qa_monitor.human_source_reference', '', true);
  RAISE;
END
$$;

