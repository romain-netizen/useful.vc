-- Phase 1 correction: make human-adjudication stamps self-verifying.
--
-- A human methodology marker is valid only when it points to a review_feedback
-- row for the same company and the feedback decision agrees with the marker.
-- Every accepted or rejected attempt is written to an append-only audit table.

BEGIN;

CREATE SCHEMA IF NOT EXISTS qa_monitor;

ALTER TABLE public.companies
  ADD COLUMN IF NOT EXISTS human_adjudication_feedback_id bigint,
  ADD COLUMN IF NOT EXISTS human_adjudication_path text;

ALTER TABLE public.criterion_reviews
  ADD COLUMN IF NOT EXISTS human_adjudication_feedback_id bigint,
  ADD COLUMN IF NOT EXISTS human_adjudication_path text;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'companies_human_adjudication_path_check'
      AND conrelid = 'public.companies'::regclass
  ) THEN
    ALTER TABLE public.companies
      ADD CONSTRAINT companies_human_adjudication_path_check
      CHECK (
        human_adjudication_path IS NULL OR human_adjudication_path IN (
          'vercel_adjudication', 'migration', 'manual', 'legacy_unrecorded'
        )
      ) NOT VALID;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'criterion_reviews_human_adjudication_path_check'
      AND conrelid = 'public.criterion_reviews'::regclass
  ) THEN
    ALTER TABLE public.criterion_reviews
      ADD CONSTRAINT criterion_reviews_human_adjudication_path_check
      CHECK (
        human_adjudication_path IS NULL OR human_adjudication_path IN (
          'vercel_adjudication', 'migration', 'manual', 'legacy_unrecorded'
        )
      ) NOT VALID;
  END IF;
END
$$;

